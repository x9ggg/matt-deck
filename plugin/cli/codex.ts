// What a file holds, or undefined when it is not there.
const readIfThere = async (path: string) => {
  try {
    return await readFile(path)
  } catch (error: any) {
    if (error.code !== 'ENOENT' && error.code !== 'ENOTDIR') {
      throw error
    }
  }
}

// The quote a TOML string opens with at i in a line, if one opens there.
const quoteAt = (line: string, i: number) => ['"""', "'''", '"', "'"].find(quote => line.startsWith(quote, i))

// Where a string opened with `quote` ends in a line, read from i: just past
// its closing quote, or -1 when the line ends first. A basic string's
// backslash escapes the character after it; a multi-line one's closing
// quote may follow up to two quotes more, its content.
const stringEnd = (line: string, i: number, quote: string) => {
  while (i < line.length) {
    if (quote[0] === '"' && line[i] === '\\') {
      i += 2
    } else if (line.startsWith(quote, i)) {
      i += quote.length
      while (quote.length === 3 && line[i] === quote[0]) {
        i++
      }
      return i
    } else {
      i++
    }
  }

  return -1
}

// The lines of a config, by index, that start inside a value: in a
// multi-line string, or in an array or an inline table not closed yet. They
// are part of that value, however they look, never a header, a key or a
// comment. Each line is read from where the last left off, its strings and
// comments skipped, the brackets in them not counted. A header's own
// brackets close on its line.
const inValues = (lines: string[]) => {
  const inside = new Set<number>()
  let open: string | undefined
  let depth = 0
  lines.forEach((line, n) => {
    let i = 0
    if (open !== undefined || depth > 0) {
      inside.add(n)
    }
    if (open !== undefined) {
      i = stringEnd(line, 0, open)
      if (i === -1) {
        return
      }
      open = undefined
    }
    while (i < line.length && line[i] !== '#') {
      const quote = quoteAt(line, i)
      if (quote === undefined) {
        if (line[i] === '[' || line[i] === '{') {
          depth++
        } else if ((line[i] === ']' || line[i] === '}') && depth > 0) {
          depth--
        }
        i++
        continue
      }
      i = stringEnd(line, i + quote.length, quote)
      if (i === -1) {
        open = quote.length === 3 ? quote : undefined
        break
      }
    }
  })

  return inside
}

// The config without Deck's registration: its table, and the tables under it,
// each from its header to the next table's. The comment lines just above that
// next header stay: Deck writes no comment, they are about the table after.
// Each line keeps its own ending, LF or CRLF.
const unregistered = (text: string) => {
  const kept: string[] = []
  let ours = false
  let above: string[] = []

  const lines = text.split(/(?<=\n)/)
  const inside = inValues(lines)
  for (const [n, line] of lines.entries()) {
    const header = inside.has(n) ? null : line.match(/^\s*\[\[?\s*([^\]]*?)\s*\]\]?\s*(?:#.*)?\r?\n?$/)
    if (header !== null) {
      const isOurs = header[1] === TABLE || header[1]!.startsWith(`${TABLE}.`)
      if (ours && !isOurs) {
        kept.push(...above)
      }
      ours = isOurs
      above = []
    }
    if (!ours) {
      kept.push(line)
    } else if (header === null) {
      above = /^\s*#/.test(line) && !inside.has(n) ? [...above, line] : []
    }
  }
  // Deck's table ran to the end: the blank line install set it apart with
  // goes with it.
  if (ours && kept.length > 0 && kept.at(-1)!.trim() === '') {
    kept.pop()
  }

  return kept.join('')
}

// The dotted key a line starts with, each part unquoted, and the text after
// it; undefined when the line starts with no key.
const keyAt = (text: string) => {
  const parts: string[] = []
  let rest = text
  for (;;) {
    const part = rest.match(/^\s*(?:([A-Za-z0-9_-]+)|"((?:[^"\\]|\\.)*)"|'([^']*)')\s*/)
    if (part === null) {
      return undefined
    }
    // A TOML basic string is a JSON string but for its escapes \UXXXXXXXX
    // and, since TOML 1.1, \xHH, written here as the JSON escape of that
    // character.
    let basic = part[2]
    try {
      basic =
        basic === undefined
          ? undefined
          : JSON.parse(
              `"${basic.replace(/\\(?:U([0-9A-Fa-f]{8})|x([0-9A-Fa-f]{2})|.)/g, (escape, long, short) =>
                long === undefined && short === undefined
                  ? escape
                  : JSON.stringify(String.fromCodePoint(parseInt(long ?? short, 16))).slice(1, -1),
              )}"`,
            )
    } catch {}
    parts.push(part[1] ?? basic ?? part[3]!)
    rest = rest.slice(part[0].length)
    if (!rest.startsWith('.')) {
      return { parts, rest }
    }
    rest = rest.slice(1)
  }
}

// What a config, its registration as install writes it taken out, still
// holds that install cannot add its table after: a registration of the Deck
// service in another form (under [mcp_servers], with spaces or quotes in its
// header, as dotted keys, in an inline table), or mcp_servers as an inline
// table. Read line by line, not parsed, the lines inside values
// left out: what it cannot tell apart, it takes for one of them, so Deck
// stops rather than writes a config Codex cannot read.
const handWritten = (text: string) => {
  let table: string[] = []
  let found: 'inline' | undefined
  const lines = text.split(/\r?\n/)
  const inside = inValues(lines)
  for (const [n, line] of lines.entries()) {
    if (inside.has(n)) {
      continue
    }
    const header = line.match(/^\s*\[\[?(.*)$/)
    const key = keyAt(header === null ? line : header[1]!)
    if (key === undefined || !key.rest.startsWith(header === null ? '=' : ']')) {
      continue
    }
    const path = header === null ? [...table, ...key.parts] : key.parts
    if (header !== null) {
      table = key.parts
    }
    if (path[0] === 'mcp_servers' && path[1] === SERVER) {
      return 'registration'
    }
    if (header === null && path.length === 1 && path[0] === 'mcp_servers') {
      // A key of the inline table itself: the first thing after its opening
      // brace or a comma in it, comments apart, not in a table or an array
      // within, nor a string or a comment. The table runs on over the lines
      // that start inside it.
      let end = n + 1
      while (inside.has(end)) {
        end++
      }
      const value = [key.rest, ...lines.slice(n + 1, end)].join('\n')
      let depth = 0
      for (let i = 1; i < value.length; ) {
        const quote = quoteAt(value, i)
        if (quote !== undefined) {
          i = stringEnd(value, i + quote.length, quote)
          if (i === -1) {
            break
          }
          continue
        }
        if (value[i] === '#') {
          i = value.indexOf('\n', i)
          if (i === -1) {
            break
          }
          continue
        }
        if (value[i] === '{' || value[i] === '[') {
          depth++
        } else if (value[i] === '}' || value[i] === ']') {
          depth--
        }
        if (
          depth === 1 &&
          (value[i] === '{' || value[i] === ',') &&
          keyAt(value.slice(i + 1).replace(/^(?:\s|#.*)*/, ''))?.parts[0] === SERVER
        ) {
          return 'registration'
        }
        i++
      }
      found = 'inline'
    }
  }

  return found
}

// Deck's hook: each prompt sent goes to the Deck service's tool as written.
// Codex trusts a hook by its place in the file and the hash of what it says,
// so it is always written the same, and never moved once there.
const HOOK = { type: 'mcp_tool', server: SERVER, tool: CODEX_HOOK_TOOL, input: { prompt: '${prompt}' }, timeout: 10 }

const isObject = (value: unknown): value is Record<string, any> =>
  typeof value === 'object' && value !== null && !Array.isArray(value)

// Why Deck leaves a hooks file alone: it holds no hooks Deck's hook can be
// added to, or it holds what Deck, writing it anew, would change.
type Refused = 'unreadable' | 'rewritten'

// The user's Codex hooks as a file holds them, {} for no file, or why Deck
// leaves them alone. Deck writes anew a file it parsed, so it handles only
// one that, written anew, differs from the text in whitespace alone: no
// number past a double, 1e400 or 1.0, no key given twice, no escape a
// string loses, no key that looks like an index and moves first. UTF-8 text
// alone, for the same reason: other bytes, decoded and written anew, change.
const hooksIn = (bytes: Buffer | undefined): Record<string, any> | Refused => {
  if (bytes === undefined) {
    return {}
  }
  if (!isUtf8(bytes)) {
    return 'unreadable'
  }
  const text = bytes.toString('utf8')
  let value: unknown
  try {
    value = JSON.parse(text)
  } catch {
    return 'unreadable'
  }
  if (!isObject(value)) {
    return 'unreadable'
  }
  const { hooks } = value
  const isAddable =
    hooks === undefined || (isObject(hooks) && (hooks.UserPromptSubmit === undefined || Array.isArray(hooks.UserPromptSubmit)))
  if (!isAddable) {
    return 'unreadable'
  }
  // The text without the whitespace between its tokens, strings kept whole.
  const tokens = text.replace(/"(?:[^"\\]|\\.)*"|[ \t\n\r]+/g, token => (token.startsWith('"') ? token : ''))

  return JSON.stringify(value) === tokens ? value : 'rewritten'
}

const isDeckHook = (handler: any) => handler?.type === 'mcp_tool' && handler?.server === SERVER && handler?.tool === CODEX_HOOK_TOOL
const holdsDeckHook = (group: any) => Array.isArray(group?.hooks) && group.hooks.some(isDeckHook)

// The hooks as install writes them: Deck's group after the others on
// UserPromptSubmit.
const withDeckHook = (config: Record<string, any>) => ({
  ...config,
  hooks: { ...config.hooks, UserPromptSubmit: [...(config.hooks?.UserPromptSubmit ?? []), { hooks: [HOOK] }] },
})

// The hooks without Deck's: its handler taken out of its group, and the
// group it leaves with no handler; then the event and the hooks it leaves
// empty, unless the hooks before install, `before`, had them.
const withoutDeckHook = (config: Record<string, any>, before: Record<string, any>) => {
  const groups = config.hooks.UserPromptSubmit.flatMap((group: any) =>
    !holdsDeckHook(group)
      ? [group]
      : group.hooks.length === 1
        ? []
        : [{ ...group, hooks: group.hooks.filter((each: any) => !isDeckHook(each)) }],
  )
  const { UserPromptSubmit: _, ...others } = config.hooks
  const hooks =
    groups.length > 0 || before.hooks?.UserPromptSubmit !== undefined ? { ...config.hooks, UserPromptSubmit: groups } : others
  const { hooks: __, ...rest } = config

  return Object.keys(hooks).length > 0 || before.hooks !== undefined ? { ...config, hooks } : rest
}

// Why a file cannot be written where it is, or made there, as a code; or
// undefined when it can. A file there is written in place, so it must take
// writing, a link the file it reaches; a file not there is made, so the
// nearest directory that is there must take a new entry. A link reaching no
// file is 'dangling': writing through it would make a file elsewhere, which
// nothing then shows is Deck's. Asked of a directory, it is whether entries
// can be made in it, removed or renamed. Checked before Deck writes anything,
// so that a run stopping for it leaves everything as it was.
const unwritable = async (path: string): Promise<string | undefined> => {
  const there = await lstat(path).catch(() => undefined)
  if (there?.isSymbolicLink() && (await stat(path).catch(() => undefined)) === undefined) {
    return 'dangling'
  }
  let reached = path
  if (there === undefined) {
    do {
      reached = dirname(reached)
    } while ((await lstat(reached).catch(() => undefined)) === undefined)
  }
  try {
    await access(reached, constants.W_OK)
  } catch (error: any) {
    return error.code ?? String(error)
  }
}

const writeJson = (path: string, value: object) => writeFile(path, `${JSON.stringify(value, null, 2)}\n`)

const args = process.argv.slice(2)

if (args.length !== 1 || (args[0] !== 'install' && args[0] !== 'uninstall')) {
  process.stderr.write(USAGE)
  process.exitCode = 2
} else {
  try {
    const config = join(homedir(), '.codex', 'config.toml')
    const configBytes = await readIfThere(config)
    const before = configBytes?.toString('utf8')
    const kept = unregistered(before ?? '')
    const skillDir = join(homedir(), '.agents', 'skills', CODEX_CONFIGURE_SKILL)
    const skill = (await readIfThere(join(skillDir, 'SKILL.md')))?.toString('utf8')
    const isOurs = skill?.includes(GENERATED) === true
    const hooksFile = join(homedir(), '.codex', 'hooks.json')
    const backup = `${hooksFile}.before-matt-deck`
    const hooksBytes = await readIfThere(hooksFile)
    const hooks = hooksIn(hooksBytes)
    const isHooked = typeof hooks !== 'string' && hooks.hooks?.UserPromptSubmit?.some(holdsDeckHook) === true

    const handwritten = handWritten(kept)

    // What install does with the hooks: a backup already there moves aside
    // unless it holds the hooks as they are, as an install that failed after
    // backing them up leaves it; that one is this install's backup already.
    const left = await lstat(backup).catch(() => undefined)
    const beforeBytes = left === undefined ? undefined : await readFile(backup).catch(() => Buffer.alloc(0))
    const isLeft = left !== undefined && !(hooksBytes !== undefined && left.isFile() && hooksBytes.equals(beforeBytes!))
    // What uninstall does with them. Unchanged since install, the hooks are
    // as they were before it: the backup, as written, and the backup goes.
    // Changed, they lose Deck's hook alone, and the backup stays. A backup
    // that holds no hooks Deck handles, or cannot be read at all, a link
    // reaching no file among them, is not what install wrote: the hooks are
    // taken for changed, and it stays as it is. With no backup, nothing shows
    // the file is Deck's: there may have been none before install, or one
    // whose backup is gone since, or Deck's hook was written in by hand. The
    // file stays, without Deck's hook.
    const beforeHooks = beforeBytes === undefined ? 'unreadable' : hooksIn(beforeBytes)
    const isRestored = typeof beforeHooks !== 'string' && typeof hooks !== 'string' && JSON.stringify(withDeckHook(beforeHooks)) === JSON.stringify(hooks)

    // Every place the run writes, makes or removes a file in, as it will.
    const skillFile = join(skillDir, 'SKILL.md')
    const touched =
      args[0] === 'install'
        ? [config, skillFile, ...(isHooked ? [] : [hooksFile, ...(isLeft || (hooksBytes !== undefined && left === undefined) ? [dirname(backup)] : [])])]
        : [
            ...(before !== undefined && kept !== before ? [config] : []),
            ...(isOurs ? [skillDir] : []),
            ...(isOurs && !(await lstat(skillDir)).isSymbolicLink() && (await readdir(skillDir)).length === 1 ? [dirname(skillDir)] : []),
            ...(isHooked ? [hooksFile, ...(isRestored ? [dirname(backup)] : [])] : []),
          ]
    let blocked: { path: string; why: string } | undefined
    for (const path of touched) {
      const why = await unwritable(path)
      if (why !== undefined) {
        blocked = { path, why }
        break
      }
    }

    if (configBytes !== undefined && !isUtf8(configBytes)) {
      // Deck writes the config back as text: a byte that is not UTF-8,
      // decoded, would come back as another.
      process.stderr.write(
        `${config} 里有不是 UTF-8 的字节，Deck 改写它时会把这些字节换掉，没有${args[0] === 'install' ? '安装' : '卸载'}，什么都没改。改好它之后再运行一次 ${args[0]}。\n`,
      )
      process.exitCode = 1
    } else if (handwritten === 'registration') {
      process.stderr.write(
        `${config} 里的 Deck 服务注册不是 Deck 认得的写法（Deck 只认单独一行的 [${TABLE}] 表头和它下面的子表，不认 [mcp_servers] 下的 ${SERVER} = { ... }、带空格或引号的表头、点分键或内联表），没有${args[0] === 'install' ? '安装' : '卸载'}，什么都没改。把它改成 [${TABLE}] 表头或者删掉之后，再运行一次 ${args[0]}。\n`,
      )
      process.exitCode = 1
    } else if (args[0] === 'install' && handwritten === 'inline') {
      process.stderr.write(
        `${config} 里的 mcp_servers 写成了内联表（mcp_servers = { ... }），Deck 没法在它下面加上自己的注册，没有安装，什么都没改。把它改成 [mcp_servers.<名字>] 这样的表之后，再运行一次 install。\n`,
      )
      process.exitCode = 1
    } else if (typeof hooks === 'string') {
      const problem = hooks === 'unreadable' ? '不是 Deck 能读懂的钩子文件' : '里有 Deck 改写时会变样的写法（超出双精度的数、1.0 或 1e400 这样重写后写法会变的数、重复的键、\\u0041、\\/ 这样重写后会变样的转义，或没有全部按数值升序排在最前面的像序号的键）'
      process.stderr.write(
        `${hooksFile} ${problem}，没有${args[0] === 'install' ? '安装' : '卸载'}，什么都没改。改好它之后再运行一次 ${args[0]}。\n`,
      )
      process.exitCode = 1
    } else if (args[0] === 'install' && skill !== undefined && !isOurs) {
      process.stderr.write(
        `${skillDir} 里已有一份不是 Deck 生成的技能 ${CODEX_CONFIGURE_SKILL}，没有安装，什么都没改。移走它之后再运行一次 install。\n`,
      )
      process.exitCode = 1
    } else if (blocked !== undefined) {
      process.stderr.write(
        `${blocked.path} ${blocked.why === 'dangling' ? '是一个链接，链到的文件不存在' : `写不进去（${blocked.why}）`}，没有${args[0] === 'install' ? '安装' : '卸载'}，什么都没改。${blocked.why === 'dangling' ? '换成文件或者删掉它' : '改好权限'}之后再运行一次 ${args[0]}。\n`,
      )
      process.exitCode = 1
    } else if (args[0] === 'install') {
      // The node registered is the first on install's PATH that is the node
      // running it, by the path found there: a package manager's link to it
      // outlives an upgrade, the versioned path the link reaches does not.
      // Node gives its own path with the links resolved. Only an absolute
      // entry: Codex starts the service from elsewhere.
      let node = process.execPath
      for (const dir of (process.env.PATH ?? '').split(delimiter)) {
        if (isAbsolute(dir) && (await realpath(join(dir, 'node')).catch(() => undefined)) === process.execPath) {
          node = join(dir, 'node')
          break
        }
      }
      // A JSON string is a TOML basic string. Deck's lines take the first line
      // ending in the config besides its registration, LF when there is none.
      const launch = [join(PLUGIN, 'server', 'main.ts'), '--host', 'codex']
      const eol = kept.match(/\r?\n/)?.[0] ?? '\n'
      const table = `[${TABLE}]${eol}command = ${JSON.stringify(node)}${eol}args = [${launch.map(arg => JSON.stringify(arg)).join(', ')}]${eol}`
      const gap = kept === '' ? '' : kept.endsWith('\n') ? eol : `${eol}${eol}`
      await mkdir(dirname(config), { recursive: true })
      await writeFile(config, `${kept}${gap}${table}`)
      await mkdir(skillDir, { recursive: true })
      await writeFile(join(skillDir, 'SKILL.md'), configureSkill)
      let moved: string | undefined
      if (!isHooked) {
        // The backup is the hooks before this install. One left there, an
        // earlier uninstall's or left when Deck's hook was taken out by hand,
        // may hold the only copy of the person's hooks: it moves first to the
        // first numbered name no file has.
        if (isLeft) {
          let n = 1
          while ((await lstat(`${backup}.${n}`).catch(() => undefined)) !== undefined) {
            n++
          }
          moved = `${backup}.${n}`
          await rename(backup, moved)
        }
        // The backup is open to whom the hooks are, and to no one more. One
        // left holding the hooks as they are is written already, and stays
        // as it is.
        if (hooksBytes !== undefined && (left === undefined || isLeft)) {
          await writeFile(backup, hooksBytes, { mode: (await stat(hooksFile)).mode & 0o777 })
        }
        await writeJson(hooksFile, withDeckHook(hooks))
        // Codex keeps trust by a hook's place in the file and its content,
        // and the hook written in may sit where none was trusted: the calls
        // received before no longer tell that it runs. Failing to forget them
        // fails no install, the hook written in already: the Pane says why
        // the local state cannot be read.
        try {
          forgetHookCalls(homedir())
        } catch {}
      }
      const hooked = isHooked
        ? `Deck 的钩子已经在 ${hooksFile} 里，没有改动。`
        : `${moved === undefined ? '' : `之前留下的备份 ${backup} 已挪到 ${moved}。`}已在 ${hooksFile} 里加上 Deck 的钩子${hooksBytes === undefined ? '' : `，原来的文件备份在 ${backup}`}。`
      process.stdout.write(
        `已把 Deck 服务注册进 ${config}。\n已生成配置技能 ${join(skillDir, 'SKILL.md')}，在 Codex 里用 $${CODEX_CONFIGURE_SKILL} 调用。\n${hooked}\n接下来两步：在终端里运行一次 codex，在钩子审查里信任 Deck 的钩子；再重启 Codex 桌面应用。之后每个 Session 的标签页菜单里出现 Matt Deck，发出的 $implement 会登记占用。\n注册和配置技能指向的是 ${PLUGIN} 这一份插件，它挪了位置或更新之后要重新运行一次 install。\n`,
      )
    } else {
      if (before === undefined || kept === before) {
        process.stdout.write(`${config} 里没有 Deck 服务的注册，没有改动。\n`)
      } else {
        await writeFile(config, kept)
        process.stdout.write(`已从 ${config} 移除 Deck 服务的注册。\n`)
      }
      if (isOurs) {
        // Only the file Deck generated goes. The directory goes after it
        // when nothing else is in it, unless it is a link: the link, and
        // what it reaches, are not Deck's.
        await rm(skillFile)
        if ((await readdir(skillDir)).length === 0 && !(await lstat(skillDir)).isSymbolicLink()) {
          await rmdir(skillDir)
        }
        process.stdout.write(`已移除 Deck 生成的配置技能 ${join(skillDir, 'SKILL.md')}。\n`)
      } else if (skill !== undefined) {
        process.stdout.write(`${skillDir} 不是 Deck 生成的，没有动它。\n`)
      }
      if (isHooked) {
        if (isRestored) {
          await writeFile(hooksFile, beforeBytes!)
          await rm(backup)
        } else {
          await writeJson(hooksFile, withoutDeckHook(hooks, typeof beforeHooks === 'string' ? {} : beforeHooks))
        }
        process.stdout.write(`已从 ${hooksFile} 移除 Deck 的钩子。\n`)
      }
      // A backup uninstall leaves, the hooks changed since install or gone,
      // is said, so the person can give back the hooks before install.
      if ((await lstat(backup).catch(() => undefined)) !== undefined) {
        process.stdout.write(`安装前的钩子文件备份留在 ${backup}，没有删。\n`)
      }
    }
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
    process.exitCode = 1
  }
}
