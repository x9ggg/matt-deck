// Run directly with Node, once a user: installs Deck into the Codex desktop
// app, or uninstalls it. Codex loads its MCP services from the user's own
// config, never a project's (ADR-0006), so the Deck service is registered
// there, started for Codex. Install also generates the configure skill as
// Codex names it, in the user's own Codex skills.
import { lstat, mkdir, readdir, readFile, realpath, rm, rmdir, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { delimiter, dirname, isAbsolute, join } from 'node:path'

import { CODEX_CONFIGURE_SKILL } from '../server/hosts.ts'

const USAGE = `Usage: node <matt-deck>/cli/codex.ts <install|uninstall>

install：把 Deck 服务注册进 Codex 的用户全局配置 ~/.codex/config.toml，原有内容保留；在 ~/.agents/skills 里生成配置技能 ${CODEX_CONFIGURE_SKILL}。装完要重启 Codex 桌面应用。注册和配置技能指向运行 install 的这一份插件，它挪了位置或更新之后要重新运行一次 install。
uninstall：从 ~/.codex/config.toml 移除 Deck 服务的注册，别的内容不动；移除 Deck 生成的 ${CODEX_CONFIGURE_SKILL}。
退出码：0 成功，1 读写失败或那里已有一份不是 Deck 生成的 ${CODEX_CONFIGURE_SKILL}，2 参数错误。
`
const TABLE = 'mcp_servers.matt_deck'
// The copy of the plugin running install, which the registration and the
// generated skill point at.
const PLUGIN = join(import.meta.dirname, '..')

// The skill install generates: one sentence sending the agent to the
// plugin's configure skill. The comment line marks it as Deck's, so a skill
// of that name someone else wrote is never overwritten or removed.
const GENERATED = '<!-- Generated by the Matt Deck install for Codex; its uninstall removes it. -->'
const configureSkill = `---
name: ${CODEX_CONFIGURE_SKILL}
description: 在 Codex 里首次配置 Matt Deck：为当前项目选定 Task Source 和 Skill Source。
---

${GENERATED}

读 \`${join(PLUGIN, 'skills', 'configure', 'SKILL.md')}\`，照它的步骤配置当前项目。
`

// What a file holds, or undefined when it is not there.
const readIfThere = async (path: string) => {
  try {
    return await readFile(path, 'utf8')
  } catch (error: any) {
    if (error.code !== 'ENOENT' && error.code !== 'ENOTDIR') {
      throw error
    }
  }
}

// The config without Deck's registration: its table, and the tables under it,
// each from its header to the next table's. The comment lines just above that
// next header stay: Deck writes no comment, they are about the table after.
// Each line keeps its own ending, LF or CRLF.
const unregistered = (text: string) => {
  const kept: string[] = []
  let ours = false
  let above: string[] = []

  for (const line of text.split(/(?<=\n)/)) {
    const header = line.match(/^\s*\[\[?\s*([^\]]*?)\s*\]\]?\s*(?:#.*)?\r?\n?$/)
    if (header !== null) {
      const isOurs = header[1] === TABLE || header[1]!.startsWith(`${TABLE}.`)
      if (ours && !isOurs) {
        kept.push(...above)
      }
      ours = isOurs
      above = []
    }
    if (!ours) {
      kept.push(line)
    } else if (header === null) {
      above = /^\s*#/.test(line) ? [...above, line] : []
    }
  }
  // Deck's table ran to the end: the blank line install set it apart with
  // goes with it.
  if (ours && kept.length > 0 && kept.at(-1)!.trim() === '') {
    kept.pop()
  }

  return kept.join('')
}

const args = process.argv.slice(2)

if (args.length !== 1 || (args[0] !== 'install' && args[0] !== 'uninstall')) {
  process.stderr.write(USAGE)
  process.exitCode = 2
} else {
  try {
    const config = join(homedir(), '.codex', 'config.toml')
    const before = await readIfThere(config)
    const kept = unregistered(before ?? '')
    const skillDir = join(homedir(), '.agents', 'skills', CODEX_CONFIGURE_SKILL)
    const skill = await readIfThere(join(skillDir, 'SKILL.md'))
    const isOurs = skill?.includes(GENERATED) === true

    if (args[0] === 'install' && skill !== undefined && !isOurs) {
      process.stderr.write(
        `${skillDir} 里已有一份不是 Deck 生成的技能 ${CODEX_CONFIGURE_SKILL}，没有安装，什么都没改。移走它之后再运行一次 install。\n`,
      )
      process.exitCode = 1
    } else if (args[0] === 'install') {
      // The node registered is the first on install's PATH that is the node
      // running it, by the path found there: a package manager's link to it
      // outlives an upgrade, the versioned path the link reaches does not.
      // Node gives its own path with the links resolved. Only an absolute
      // entry: Codex starts the service from elsewhere.
      let node = process.execPath
      for (const dir of (process.env.PATH ?? '').split(delimiter)) {
        if (isAbsolute(dir) && (await realpath(join(dir, 'node')).catch(() => undefined)) === process.execPath) {
          node = join(dir, 'node')
          break
        }
      }
      // A JSON string is a TOML basic string.
      const launch = [join(PLUGIN, 'server', 'main.ts'), '--host', 'codex']
      const table = `[${TABLE}]\ncommand = ${JSON.stringify(node)}\nargs = [${launch.map(arg => JSON.stringify(arg)).join(', ')}]\n`
      const gap = kept === '' ? '' : kept.endsWith('\n') ? '\n' : '\n\n'
      await mkdir(dirname(config), { recursive: true })
      await writeFile(config, `${kept}${gap}${table}`)
      await mkdir(skillDir, { recursive: true })
      await writeFile(join(skillDir, 'SKILL.md'), configureSkill)
      process.stdout.write(
        `已把 Deck 服务注册进 ${config}。\n已生成配置技能 ${join(skillDir, 'SKILL.md')}，在 Codex 里用 $${CODEX_CONFIGURE_SKILL} 调用。\n重启 Codex 桌面应用之后，每个 Session 的标签页菜单里出现 Matt Deck。\n注册和配置技能指向的是 ${PLUGIN} 这一份插件，它挪了位置或更新之后要重新运行一次 install。\n`,
      )
    } else {
      if (before === undefined || kept === before) {
        process.stdout.write(`${config} 里没有 Deck 服务的注册，没有改动。\n`)
      } else {
        await writeFile(config, kept)
        process.stdout.write(`已从 ${config} 移除 Deck 服务的注册。\n`)
      }
      if (isOurs) {
        // Only the file Deck generated goes. The directory goes after it
        // when nothing else is in it, unless it is a link: the link, and
        // what it reaches, are not Deck's.
        await rm(join(skillDir, 'SKILL.md'))
        if ((await readdir(skillDir)).length === 0 && !(await lstat(skillDir)).isSymbolicLink()) {
          await rmdir(skillDir)
        }
        process.stdout.write(`已移除 Deck 生成的配置技能 ${join(skillDir, 'SKILL.md')}。\n`)
      } else if (skill !== undefined) {
        process.stdout.write(`${skillDir} 不是 Deck 生成的，没有动它。\n`)
      }
    }
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
    process.exitCode = 1
  }
}
