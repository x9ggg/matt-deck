// Task kernel: the skills of a project's Skill Source, read and never
// written. Host-agnostic: it knows a workspace, a home directory and how the
// host calls a skill, a rule it is handed.
import type { Dirent } from 'node:fs'
import { readdir, readFile, realpath, stat } from 'node:fs/promises'
import { basename, dirname, isAbsolute, join } from 'node:path'

import type { ProjectConfig } from './config.ts'

type SkillSource = ProjectConfig['skillSource']

// How the host calls a skill: by its name, and by the plugin's name when the
// Skill Source is a plugin.
export type CallOf = (name: string, plugin: string | undefined) => string

// A skill as the Pane lists it: `call` is how this Session invokes it, as
// its host writes it; `path` is its file, `~` for the home.
export type Skill = { name: string; call: string; description: string; path: string }

// What the host calls by a skill's name, among the skill files it finds in
// its own skill directories, known by the names their frontmatter gives:
// exactly one file, its links resolved, and it is the Skill Source's; another
// file; or none, as for a name the host cannot call.
export type HostCopy = 'same' | 'different' | 'missing'

// Why the Skill Source cannot be read: it is not there, or holds no skill of
// that name.
export class SkillSourceError extends Error {
  kind: 'missing' | 'unknown-skill'
  constructor(kind: SkillSourceError['kind'], message: string) {
    super(message)
    this.kind = kind
  }
}

// The line marking a skill file Deck generated, as Codex install generates
// its configure skill: it is not one of the Skill Source's skills, so Deck
// neither lists nor reads it, for any host. Install writes it, and knows its
// own file by it.
export const GENERATED_MARK = '<!-- Generated by the Matt Deck install for Codex; its uninstall removes it. -->'

const isMissing = (error: any) => error.code === 'ENOENT' || error.code === 'ENOTDIR'

// A directory written as a Skill Source's path is: `~/...` under the home,
// otherwise absolute or relative to the Workspace.
const resolveDirectory = (path: string, workspace: string, home: string) =>
  path.startsWith('~/') ? join(home, path.slice(2)) : isAbsolute(path) ? path : join(workspace, path)

// The frontmatter's `key: value` fields, and the body under it. A value
// written as a block (`>` or `|`, then indented lines) is read as one line:
// the Pane lists a description on one.
const parse = (text: string) => {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/)
  const fields: Record<string, string> = {}
  let block: string | undefined
  for (const line of match?.[1]?.split(/\r?\n/) ?? []) {
    const field = line.match(/^([\w-]+):\s*(.*?)\s*$/)
    if (field !== null) {
      block = /^[>|][+-]?$/.test(field[2]!) ? field[1]! : undefined
      fields[field[1]!] = block === undefined ? field[2]!.replace(/^(["'])(.*)\1$/, '$2') : ''
    } else if (block !== undefined && line.trim() !== '') {
      fields[block] = `${fields[block]} ${line.trim()}`.trimStart()
    }
  }

  return { fields, body: text.slice(match?.[0].length ?? 0).replace(/^\s*\n/, '') }
}

// Where the skill files are: the root they lie under, how a path under it is
// written, the plugin holding them, if one does, and the files relative to
// the root.
const locate = async (source: SkillSource, workspace: string, home: string) => {
  const tilde = (path: string) => (path.startsWith(`${home}/`) ? `~${path.slice(home.length)}` : path)
  if (source.type === 'directory') {
    const root = resolveDirectory(source.path, workspace, home)
    let entries: string[]
    try {
      entries = await readdir(root)
    } catch (error: any) {
      if (isMissing(error)) {
        throw new SkillSourceError('missing', `the directory ${source.path} does not exist`)
      }
      throw error
    }

    return {
      root,
      shown: (file: string) => `${source.path}/${file}`,
      plugin: undefined,
      files: entries.map(entry => `${entry}/SKILL.md`),
    }
  }

  let installed: string | undefined
  try {
    installed = await readFile(join(home, '.claude', 'plugins', 'installed_plugins.json'), 'utf8')
  } catch (error: any) {
    if (!isMissing(error)) {
      throw error
    }
  }
  const plugins: Record<string, { scope: string; projectPath?: string; installPath: string }[]> =
    installed === undefined ? {} : JSON.parse(installed).plugins
  const install = Object.entries(plugins)
    .filter(([key]) => key.split('@')[0] === source.name)
    .flatMap(([, installs]) => installs)
    .find(({ scope, projectPath }) => scope === 'user' || projectPath === workspace)
  if (install === undefined) {
    throw new SkillSourceError('missing', `the plugin ${source.name} is not installed`)
  }
  const root = join(install.installPath, 'skills')
  let files: string[]
  try {
    files = await readdir(root, { recursive: true })
  } catch (error: any) {
    if (isMissing(error)) {
      throw new SkillSourceError('missing', `the plugin ${source.name} has no skills directory`)
    }
    throw error
  }

  return {
    root,
    shown: (file: string) => tilde(join(root, file)),
    plugin: source.name,
    files: files.filter(file => file === 'SKILL.md' || file.endsWith('/SKILL.md')),
  }
}

// Every skill of the Skill Source with its text, by name: a Skill Source has
// no order of its own, and a plugin's folders are not shown.
const readAll = async (source: SkillSource, workspace: string, home: string, callOf: CallOf) => {
  const { root, shown, plugin, files } = await locate(source, workspace, home)
  const skills: (Skill & { text: string; file: string })[] = []
  for (const file of files) {
    let text: string
    try {
      text = await readFile(join(root, file), 'utf8')
    } catch (error: any) {
      if (isMissing(error)) {
        continue
      }
      throw error
    }
    if (text.includes(GENERATED_MARK)) {
      continue
    }
    const { fields, body } = parse(text)
    const name = fields.name || file.split('/').at(-2)!
    skills.push({ name, call: callOf(name, plugin), description: fields.description ?? '', path: shown(file), text: body, file: join(root, file) })
  }

  return skills.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
}

// How deep Codex looks for skill folders under each of its skill
// directories (`MAX_SCAN_DEPTH` in codex-rs/ext/skills/src/loader/mod.rs).
const CODEX_SCAN_DEPTH = 6

// Every skill file the host finds itself under `directories`, its links
// resolved, with the name the host knows it by: its frontmatter's `name`, or
// when that is empty the name of its folder, links resolved. The directories
// are walked as Codex walks its own: down to CODEX_SCAN_DEPTH levels, each
// directory once under each of them, following links to directories but not
// to files, and never into a hidden directory.
const scanHost = async (directories: string[], workspace: string, home: string) => {
  const found: { name: string; file: string }[] = []
  for (const directory of directories) {
    const queue = [{ dir: resolveDirectory(directory, workspace, home), depth: 0 }]
    const visited = new Set<string>()
    while (queue.length > 0) {
      const { dir, depth } = queue.shift()!
      // What cannot be read, Codex passes over: a link in a loop, a
      // directory or file it may not read.
      const real = await realpath(dir).catch(() => undefined)
      if (real === undefined || visited.has(real)) {
        continue
      }
      visited.add(real)
      const entries = await readdir(dir, { withFileTypes: true }).catch(() => [] as Dirent[])
      for (const entry of entries) {
        const path = join(dir, entry.name)
        const kind = entry.isSymbolicLink() ? await stat(path).catch(() => undefined) : entry
        if (kind?.isDirectory()) {
          if (depth < CODEX_SCAN_DEPTH && !entry.name.startsWith('.')) {
            queue.push({ dir: path, depth: depth + 1 })
          }
        } else if (entry.isFile() && entry.name === 'SKILL.md') {
          const text = await readFile(path, 'utf8').catch(() => undefined)
          if (text !== undefined) {
            const file = await realpath(path)
            found.push({ name: parse(text).fields.name || basename(dirname(file)), file })
          }
        }
      }
    }
  }

  return found
}

// What the host finds under its name, as the Skill Source's file at `file`
// is to it: the one file of that name is this one, another file is, or none.
// A name holding a character Codex's `$` does not take calls nothing.
const hostCopy = async (file: string, name: string, found: { name: string; file: string }[]): Promise<HostCopy> => {
  if (!/^[A-Za-z0-9_:-]+$/.test(name)) {
    return 'missing'
  }
  const own = await realpath(file)
  const files = new Set(found.filter(each => each.name === name).map(each => each.file))

  return files.size === 0 ? 'missing' : files.size === 1 && files.has(own) ? 'same' : 'different'
}

// What the host calls by a name, from one walk of its own skill directories:
// for the Skill Source's file at `file` named `name`, its HostCopy.
export const hostCopies = async (directories: string[], workspace: string, home: string) => {
  const found = await scanHost(directories, workspace, home)

  return (file: string, name: string) => hostCopy(file, name, found)
}

// The skills of the Skill Source. Given the directories a host finds skills
// in itself, each also says what the host finds there under its name.
export const listSkills = async (
  source: SkillSource,
  workspace: string,
  home: string,
  callOf: CallOf,
  hostDirectories?: string[],
): Promise<(Skill & { copy?: HostCopy })[]> => {
  const skills = await readAll(source, workspace, home, callOf)
  const copyOf = hostDirectories === undefined ? undefined : await hostCopies(hostDirectories, workspace, home)
  const listed = []
  for (const { text, file, ...skill } of skills) {
    listed.push(
      copyOf === undefined ? skill : { ...skill, copy: await copyOf(file, skill.name) },
    )
  }

  return listed
}

// One skill with its text: the skill file under its frontmatter, as written.
export const readSkill = async (source: SkillSource, workspace: string, home: string, callOf: CallOf, name: string) => {
  const skill = (await readAll(source, workspace, home, callOf)).find(skill => skill.name === name)
  if (skill === undefined) {
    throw new SkillSourceError('unknown-skill', `the Skill Source has no skill named ${name}`)
  }

  const { file, ...read } = skill

  return read
}
